/* ---- 生成ヘルパー ---- */
function sec(title, body) {
  if (!body) return null;
  return "【" + title + "】\n" + body;
}
function bullets(arr) {
  const list = arr.filter(Boolean);
  return list.length ? list.map((s) => "- " + s).join("\n") : null;
}
function block(parts) {
  return parts.filter(Boolean).join("\n\n");
}

